import Link from "next/link";
import { notFound } from "next/navigation";
import type { Metadata } from "next";
import { BasisBadge, Chips } from "@/components/ui";
import { getFaculty, getPaper, getPapers } from "@/lib/content";

export const dynamicParams = false;

export function generateStaticParams() {
  return getPapers().map((p) => ({ id: p.id }));
}

export async function generateMetadata({ params }: { params: Promise<{ id: string }> }): Promise<Metadata> {
  const p = getPaper((await params).id);
  return p ? { title: p.title, description: p.summary?.oneLiner ?? p.abstract?.slice(0, 200) } : {};
}

const TYPE_LABEL: Record<string, string> = {
  article: "Journal article",
  preprint: "Working paper",
  book: "Book",
  "book-chapter": "Book chapter",
  review: "Review",
};

function sourceLine(s: NonNullable<ReturnType<typeof getPaper>>["summary"]) {
  if (!s) return null;
  const src = s.source;
  if (src.kind === "claude-research") return `Summary researched and written ${src.createdAt} from the paper and public sources.`;
  if (src.kind === "faculty") return `Summary reviewed by the author${src.note ? ` — ${src.note}` : ""}.`;
  return `Draft summary generated by ${src.model} (${src.prompt}) on ${src.createdAt}; pending review.`;
}

export default async function PaperPage({ params }: { params: Promise<{ id: string }> }) {
  const p = getPaper((await params).id);
  if (!p) notFound();
  const names = Object.fromEntries(getFaculty().map((f) => [f.slug, f.name]));
  const s = p.summary;
  const authors = p.authors.slice(0, 15);

  return (
    <>
      <div className="crumbs">
        <Link href="/">Home</Link> /{" "}
        {p.isb[0] ? <><Link href={`/faculty/${p.isb[0]}`}>{names[p.isb[0]]}</Link> / </> : null}
        Paper
      </div>

      <div className="card paper-head" style={{ padding: "1.5rem 1.7rem" }}>
        <div className="meta">
          <BasisBadge summary={s} />
          {[p.type ? TYPE_LABEL[p.type] ?? p.type : null, p.year, p.venue].filter(Boolean).join(" · ")}
          {p.citations > 0 ? <span>· {p.citations.toLocaleString()} citations</span> : null}
        </div>
        <h1>{p.title}</h1>
        <div className="meta">
          {authors.map((a, i) => (
            <span key={i}>
              {a.isb ? <Link href={`/faculty/${a.isb}`}><b>{a.name}</b></Link> : a.name}
              {i < authors.length - 1 ? "," : ""}
            </span>
          ))}
          {p.authors.length > authors.length ? <span>and {p.authors.length - authors.length} others</span> : null}
        </div>
        <div className="links">
          {p.doi ? <a href={p.doi} target="_blank" rel="noreferrer">DOI ↗</a> : null}
          {p.url && p.url !== p.doi ? <a href={p.url} target="_blank" rel="noreferrer">Publisher page ↗</a> : null}
          {p.pdf ? <a href={p.pdf} target="_blank" rel="noreferrer">Open-access PDF ↗</a> : null}
          <a href={`https://openalex.org/${p.id}`} target="_blank" rel="noreferrer">OpenAlex ↗</a>
        </div>
      </div>

      {s ? (
        <>
          <div className="oneliner">{s.oneLiner}</div>
          {s.basis === "abstract_only" ? (
            <div className="notice soft">
              This summary is based on the <b>abstract only</b>; the full paper wasn&apos;t available, so details may be missing.
            </div>
          ) : null}
          <div className="lead">{s.overview}</div>
          <div className="grid3">
            <div className="field"><div className="k">Research question</div><div className="v">{s.question}</div></div>
            <div className="field"><div className="k">Method</div><div className="v">{s.method}</div></div>
            <div className="field"><div className="k">Data</div><div className="v">{s.data}</div></div>
          </div>
          <div className="section">Key findings</div>
          <ul className="findings">{s.findings.map((x, i) => <li key={i}>{x}</li>)}</ul>
          <div className="section">Why it matters</div>
          <div className="lead">{s.whyItMatters}</div>
          <div className="section">Topics</div>
          <Chips items={s.topics} />
          {[...(s.industries ?? []), ...(s.geographies ?? [])].length ? (
            <div className="small" style={{ marginTop: ".5rem" }}>
              Context: {[...(s.industries ?? []), ...(s.geographies ?? [])].join(", ")}
            </div>
          ) : null}
          {p.abstract ? (
            <details className="abstract">
              <summary>Original abstract</summary>
              <div className="lead" style={{ fontSize: ".93rem" }}>{p.abstract}</div>
            </details>
          ) : null}
          {s.source.kind === "claude-research" && s.source.sources.length ? (
            <>
              <div className="section">Sources used</div>
              <ul className="findings small">
                {s.source.sources.map((u) => <li key={u}><a href={u} target="_blank" rel="noreferrer">{u}</a></li>)}
              </ul>
            </>
          ) : null}
          <div className="small" style={{ marginTop: "1.2rem" }}>{sourceLine(s)}</div>
        </>
      ) : (
        <>
          <div className="notice">No plain-English summary yet.</div>
          {p.abstract ? (
            <>
              <div className="section">Abstract</div>
              <div className="lead">{p.abstract}</div>
            </>
          ) : null}
        </>
      )}

      {p.versions.length ? (
        <>
          <div className="section">Other versions</div>
          <ul className="findings small">
            {p.versions.map((v) => (
              <li key={v.id}>
                {[v.type ? TYPE_LABEL[v.type] ?? v.type : null, v.venue, v.year].filter(Boolean).join(" · ")}
                {v.url ? <> · <a href={v.url} target="_blank" rel="noreferrer">link ↗</a></> : null}
              </li>
            ))}
          </ul>
        </>
      ) : null}

      <div className="section">ISB faculty on this paper</div>
      <div className="links">
        {p.isb.map((slug) => <Link key={slug} href={`/faculty/${slug}`}>{names[slug]}</Link>)}
      </div>
    </>
  );
}
